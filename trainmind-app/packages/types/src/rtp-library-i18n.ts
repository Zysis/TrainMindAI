export const RTP_LIBRARY_I18N: Record<RtpLibraryLocale, Record<string, string>> = { en: EN, es: ES };

/**
 * Testo del protocollo nella lingua attiva.
 *
 * `fallback` e' sempre la stringa che arriva dal database: in italiano, per un
 * protocollo dell'organizzazione o per una chiave non ancora tradotta e' la
 * risposta giusta, non un ripiego.
 */
export function rtpText(locale: string, key: string | null, fallback: string): string;
export function rtpText(locale: string, key: string | null, fallback: string | null): string | null;
export function rtpText(locale: string, key: string | null, fallback: string | null): string | null {
  if (!key || locale === 'it') return fallback;
  const table = RTP_LIBRARY_I18N[locale as RtpLibraryLocale];
  return (table && table[key]) ?? fallback;
}

/** Chiave del nome/descrizione di un protocollo di sistema. */
export function rtpTemplateKey(code: string | null | undefined): string | null {
  return code ? code : null;
}

/** Chiave di una fase: `<code>.p<order>`, con `#g` per l'obiettivo. */
export function rtpPhaseKey(code: string | null | undefined, order: number): string | null {
  return code ? `${code}.p${order}` : null;
}

/** Chiave di un criterio: `<code>.p<phaseOrder>.c<order>`. */
export function rtpCriterionKey(
  code: string | null | undefined,
  phaseOrder: number,
  order: number,
): string | null {
  return code ? `${code}.p${phaseOrder}.c${order}` : null;
}

/** Nome del test tradotto. Non dipende dal protocollo: la chiave e' il testo italiano. */
export function rtpTestName(locale: string, testCode: string | null): string | null {
  return rtpText(locale, testCode ? `#t:${testCode}` : null, testCode);
}

/** Unita' di misura tradotta (`gradi` -> `degrees`). */
export function rtpUnit(locale: string, unit: string | null): string | null {
  return rtpText(locale, unit ? `#u:${unit}` : null, unit);
}
